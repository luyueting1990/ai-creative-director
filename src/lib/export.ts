import { LINK_LABELS, classifyLink } from "./links";
import { PLATFORM_LABELS, campaignDuration, campaignPlatforms, type Concept, type PhotoMeta, type Project } from "./schema";
import { totalDuration } from "./editor";

function cell(s: string | number): string {
  return String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export type ExportableProject = Pick<Project, "name" | "brief" | "campaign" | "selectedConceptId"> & {
  photos?: PhotoMeta[];
};

/**
 * Renders a campaign as a client-ready Markdown document: the chosen concept
 * in full (storyboard, production notes, social copy) and the two
 * alternatives in brief.
 */
export function projectToMarkdown(project: ExportableProject): string {
  const { brief, campaign } = project;
  const chosen = campaign.concepts.find((c) => c.id === project.selectedConceptId) ?? campaign.concepts[0];
  const others = campaign.concepts.filter((c) => c.id !== chosen.id);
  const photos = project.photos ?? [];

  return [
    `# ${project.name}`,
    "",
    campaign.source === "demo"
      ? "> Created in demo mode by a rule-based engine from the brief text. Photos and links were not analysed."
      : `> Generated by Claude (${campaign.model ?? "unknown model"}). Review before sharing.`,
    "",
    "## Brief",
    "",
    `- **Brand:** ${brief.brandName} — ${brief.brandDescription}`,
    `- **Product:** ${brief.productDescription}`,
    `- **Goal:** ${brief.goal}`,
    ...(brief.audience ? [`- **Audience:** ${brief.audience}`] : []),
    `- **Platforms:** ${campaignPlatforms(brief).map((p) => PLATFORM_LABELS[p]).join(", ")} · **Film:** ${campaignDuration(brief)}s`,
    ...(photos.length ? [`- **Reference photos:** ${photos.map((p) => p.name).join(", ")}`] : []),
    ...(brief.links.length ? ["- **Links:**", ...brief.links.map((u) => `  - ${LINK_LABELS[classifyLink(u)]}: ${u}`)] : []),
    "",
    ...conceptSection(chosen),
    "## Other concepts",
    "",
    ...others.map((c) => `- **${c.title}** — ${c.idea}`),
    "",
    `_Exported ${new Date().toUTCString()}_`,
    "",
  ].join("\n");
}

function conceptSection(c: Concept): string[] {
  return [
    `## Concept: ${c.title}`,
    "",
    c.idea,
    "",
    `_${c.rationale}_`,
    "",
    `**Look.** ${c.look.setting}. ${c.look.lighting}. ${c.look.styling}.`,
    "",
    `**Palette.** ${c.palette.map((s) => `${s.name} \`${s.hex}\``).join(" · ")} · **Music.** ${c.music}`,
    "",
    `### Storyboard (${c.shots.length} shots, ${totalDuration(c.shots)}s)`,
    "",
    "| # | Shot | Description | On screen | Camera | Setting | Direction | Sec |",
    "|---|---|---|---|---|---|---|---|",
    ...c.shots.map(
      (s, i) =>
        `| ${i + 1} | ${cell(s.title)}${s.showsProduct ? " ★" : ""} | ${cell(s.description)} | ${cell(s.onScreenText || "—")} | ${cell(s.camera)} | ${cell(s.setting)} | ${cell(s.direction)} | ${s.durationSec} |`,
    ),
    "",
    "★ = shows the product",
    "",
    "### Hooks",
    "",
    ...c.hooks.map((h) => `- **${PLATFORM_LABELS[h.platform]}:** ${h.text}`),
    "",
    "### Captions",
    "",
    ...c.captions.flatMap((cap) => [
      `**${PLATFORM_LABELS[cap.platform]}** — ${cap.text}${cap.hashtags.length ? ` ${cap.hashtags.join(" ")}` : ""}`,
      "",
    ]),
  ];
}

export function slugify(s: string): string {
  return (
    s
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 60) || "campaign"
  );
}

export function downloadFile(filename: string, content: string, type: string) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
