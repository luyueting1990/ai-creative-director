import { LINK_LABELS, classifyLink } from "./links";
import {
  PLATFORM_LABELS,
  campaignDuration,
  campaignPlatforms,
  type Brief,
  type Concept,
  type PhotoMeta,
  type Project,
} from "./schema";
import { totalDuration } from "./editor";

function cell(s: string | number): string {
  return String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
}

type ExportableProject = Pick<Project, "name" | "brief" | "campaign"> & { photos?: PhotoMeta[] };

/** Renders a project as a client-ready Markdown treatment. */
export function projectToMarkdown(project: ExportableProject): string {
  const { brief, campaign } = project;
  const o = campaign.overview;
  const lines: string[] = [
    `# ${project.name}`,
    "",
    campaign.source === "demo"
      ? "> **Illustrative demo content.** Generated by the demo engine from the brief text. Photos, links and videos were not analysed."
      : `> Generated by Claude (${campaign.model ?? "unknown model"}). Review before sharing with a client.`,
    "",
    briefSection(brief, project.photos ?? []),
    "",
    "## Brand overview",
    "",
    o.summary,
    "",
    `**Positioning.** ${o.positioning}`,
    "",
    `**Audience.** ${o.audienceInsight}`,
    "",
    `**Tone.** ${o.toneKeywords.join(" · ")}`,
    "",
    ...o.pillars.map((p) => `- **${p.title}** — ${p.description}`),
    "",
    ...campaign.concepts.flatMap((c, i) => conceptSection(c, i + 1)),
    `_Generated ${new Date(campaign.generatedAt).toUTCString()}_`,
    "",
  ];
  return lines.join("\n");
}

function briefSection(b: Brief, photos: PhotoMeta[]): string {
  const links = [...b.socialLinks, ...b.websiteLinks, ...b.videoLinks];
  return [
    "## Brief",
    "",
    `- **Brand:** ${b.brandName}`,
    `- **Brand description:** ${b.brandDescription}`,
    `- **Product / collection:** ${b.productDescription}`,
    `- **Goal:** ${b.goal}`,
    ...(b.audience ? [`- **Audience:** ${b.audience}`] : []),
    `- **Platforms:** ${campaignPlatforms(b).map((p) => PLATFORM_LABELS[p]).join(", ")}`,
    `- **Film length:** ${campaignDuration(b)}s`,
    ...(photos.length ? [`- **Product photos:** ${photos.map((p) => p.name).join(", ")}`] : []),
    ...(links.length ? ["- **Reference links:**", ...links.map((u) => `  - ${LINK_LABELS[classifyLink(u)]}: ${u}`)] : []),
  ].join("\n");
}

function conceptSection(c: Concept, n: number): string[] {
  const m = c.moodboard;
  return [
    `## Concept ${n}: ${c.title}`,
    "",
    `> ${c.tagline}`,
    "",
    `**Big idea.** ${c.bigIdea}`,
    "",
    ...(c.whyItWorks ? [`**Why it works.** ${c.whyItWorks}`, ""] : []),
    `**Visual direction.** ${c.visualDirection}`,
    "",
    "### Moodboard",
    "",
    `- **Keywords:** ${m.keywords.join(", ")}`,
    `- **Lighting:** ${m.lighting}`,
    `- **Styling:** ${m.styling}`,
    `- **Locations:** ${m.locations}`,
    `- **References:** ${m.references.join("; ")}`,
    `- **Palette:** ${c.palette.map((s) => `${s.name} \`${s.hex}\``).join(" · ")}`,
    `- **Soundtrack:** ${c.soundtrack}`,
    "",
    `### Storyboard (${totalDuration(c.storyboard)}s)`,
    "",
    "| # | Frame | Visual | Audio | On-screen text | Sec |",
    "|---|---|---|---|---|---|",
    ...c.storyboard.map(
      (f, i) =>
        `| ${i + 1} | ${cell(f.title)}${f.featuresProduct ? " ★" : ""} | ${cell(f.visual)} | ${cell(f.audio)} | ${cell(f.onScreenText || "—")} | ${f.durationSec} |`,
    ),
    "",
    "### Shot list",
    "",
    "| # | Shot | Action | Camera | Movement | Lighting | Location | Talent | Direction | Sec |",
    "|---|---|---|---|---|---|---|---|---|---|",
    ...c.shotList.map(
      (s, i) =>
        `| ${i + 1} | ${cell(s.shotType)} | ${cell(s.description)} | ${cell(s.camera)} | ${cell(s.movement)} | ${cell(s.lighting)} | ${cell(s.location)} | ${cell(s.talent)} | ${cell(s.direction)} | ${s.durationSec} |`,
    ),
    "",
    "### Hooks",
    "",
    ...c.hooks.map((h) => `- **${PLATFORM_LABELS[h.platform]}:** ${h.text}`),
    "",
    "### Captions",
    "",
    ...c.captions.flatMap((cap) => [
      `**${PLATFORM_LABELS[cap.platform]}** — ${cap.text}${cap.hashtags.length ? ` ${cap.hashtags.join(" ")}` : ""}`,
      "",
    ]),
  ];
}

export function slugify(s: string): string {
  return (
    s
      .toLowerCase()
      .normalize("NFKD")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 60) || "campaign"
  );
}

export function downloadFile(filename: string, content: string, type: string) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
